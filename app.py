"""
Financial Trade Reconciliation Dashboard

This Streamlit app displays trading activity, price trends,
and position reconciliation results.

Required outputs from reconciliation.py:

CSV files:
- reports/cleaned_trades.csv
- reports/full_reconciliation.csv

PNG files:
- reports/trading_volume.png
- reports/reconciliation_rate.png
- reports/reconciliation_difference.png

Note:
- reports/price_trend.png is also generated by reconciliation.py,
  but this dashboard creates interactive price charts from CSV data.

How to Run:
1. Run reconciliation.py to generate the required CSV and PNG files.
2. Open a terminal in the project directory.
3. Run the following command:

   streamlit run app.py
"""
import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from io import BytesIO

# Page configuration
st.set_page_config(
    page_title="Financial Trade Reconciliation",
    layout="wide"
)

# Navigation menu
st.markdown("""
<div style="display: flex; gap: 20px; flex-wrap: wrap;">
    <a href="#trading-volume">Trading Volume</a>
    <a href="#price-trend">Price Trend</a>
    <a href="#reconciliation-rate">Reconciliation Rate</a>
    <a href="#reconciliation-differences">Differences</a>
    <a href="#reconciliation-results">Results</a>
</div>
<hr>
""", unsafe_allow_html=True)

st.title("Financial Trade Reconciliation Dashboard")

st.write(
    "This dashboard summarizes trading activity, "
    "price trends, and position reconciliation results."
)

# Load reconciliation results
recon = pd.read_csv("reports/full_reconciliation.csv")

# Load cleaned trade data for price trend
df_clean = pd.read_csv(
    "reports/cleaned_trades.csv",
    parse_dates=["trade_date"]
)

# Summary metrics
total = len(recon)
matched = (recon["status"] == "MATCH").sum()
mismatched = (recon["status"] == "MISMATCH").sum()
invalid = (recon["status"] == "INVALID").sum()

col1, col2, col3, col4 = st.columns(4)

col1.metric("Total Symbols", total)
col2.metric("Matched", matched)
col3.metric("Mismatched", mismatched)
col4.metric("Invalid", invalid)

st.divider()

# Chart 1: Trading Volume
st.markdown('<div id="trading-volume"></div>', unsafe_allow_html=True)
st.subheader("1. Which symbols had the highest trading volume?")
st.image("reports/trading_volume.png", width=850)

st.caption(
    "Insight: AAPL had the highest trading volume, "
    "followed by GOOGL and META."
)

# Chart 2: Price Trend
st.markdown(
    '<div id="price-trend"></div>',
    unsafe_allow_html=True
)

st.subheader("2. How did the price evolve over time?")

# Calculate daily average prices
price_trend = (
    df_clean
    .groupby(["trade_date", "symbol"], as_index=False)["price"]
    .mean()
)

# Assign a consistent color to each symbol
symbols = sorted(df_clean["symbol"].unique())
colors = dict(zip(symbols, sns.color_palette("tab10", len(symbols))))

# 1) Overall price trend
st.write("**Overall Price Trend**")

fig, ax = plt.subplots(figsize=(9, 4))

sns.lineplot(
    data=price_trend,
    x="trade_date",
    y="price",
    hue="symbol",
    hue_order=symbols,
    palette=colors,
    marker="o",
    ax=ax
)

ax.set_xlabel("Trade Date")
ax.set_ylabel("Average Trade Price ($)")
ax.legend(title="Symbol", bbox_to_anchor=(1.02, 1), loc="upper left")
fig.autofmt_xdate()
fig.tight_layout()

buffer = BytesIO()
fig.savefig(buffer, format="png", dpi=100, bbox_inches="tight")
buffer.seek(0)

st.image(buffer, width=800)
plt.close(fig)

# 2) Individual symbol price trend
st.write("**Price Trend by Symbol**")

selected_symbol = st.selectbox(
    "Choose a symbol:",
    symbols
)

filtered_price = price_trend[
    price_trend["symbol"] == selected_symbol
]

fig, ax = plt.subplots(figsize=(9, 3.5))

ax.plot(
    filtered_price["trade_date"],
    filtered_price["price"],
    color=colors[selected_symbol],
    marker="o"
)

ax.set_title(f"{selected_symbol} Price Trend")
ax.set_xlabel("Trade Date")
ax.set_ylabel("Average Trade Price ($)")
fig.autofmt_xdate()
fig.tight_layout()

buffer = BytesIO()
fig.savefig(buffer, format="png", dpi=100, bbox_inches="tight")
buffer.seek(0)

st.image(buffer, width=800)
plt.close(fig)

st.caption(
    "Insight: Average trade prices fluctuated across symbols "
    "during the period. Select a symbol to explore its trend."
)

# Chart 3: Reconciliation Rate
st.markdown('<div id="reconciliation-rate"></div>', unsafe_allow_html=True)
st.subheader("3. Reconciliation Status by Symbol")
st.image("reports/reconciliation_rate.png", width=850)

match_rate = matched / total * 100 if total else 0

st.caption(
    f"Insight: {match_rate:.1f}% of symbols reconciled correctly, "
    f"while {mismatched / total * 100:.1f}% showed mismatches "
    f"and {invalid / total * 100:.1f}% were invalid."
    if total else "No reconciliation results available."
)

# Chart 4: Reconciliation Difference
st.markdown('<div id="reconciliation-differences"></div>', unsafe_allow_html=True)
st.subheader("4. Which symbols had the largest reconciliation differences?")
st.image("reports/reconciliation_difference.png", width=850)

st.caption(
    "Insight: XOM had the largest absolute reconciliation difference."
)

st.divider()

# Reconciliation results table
st.markdown('<div id="reconciliation-results"></div>', unsafe_allow_html=True)
st.subheader("Reconciliation Results")

summary_columns = [
    "symbol",
    "position_t0",
    "position_t1",
    "net_qty",
    "corp_shares",
    "recon_diff",
    "status"
]

st.dataframe(
    recon[summary_columns],
    hide_index=True
)

# Show full reconciliation details
with st.expander("View Full Reconciliation Data"):
    st.dataframe(
        recon,
        hide_index=True
    )